# JWT expiry: 30 minutes (NFR-SEC-003)
JWT_EXPIRY_SECONDS = 30 * 60

# PBKDF2 scheme identifier written by init_db.py seed accounts
_PBKDF2_PREFIX = "pbkdf2$"


# ---------------------------------------------------------------------------
# 1. Password Utilities
# ---------------------------------------------------------------------------

def hash_password(plaintext: str) -> str:
    """
    Hash a plaintext password using bcrypt.
    Returns a utf-8 decoded string suitable for TEXT column storage.
    Called exclusively during registration (NFR-SEC-001).
    """
    salt = bcrypt.gensalt(rounds=12)
    hashed = bcrypt.hashpw(plaintext.encode("utf-8"), salt)
    return hashed.decode("utf-8")


def verify_password(plaintext: str, stored_hash: str) -> bool:
    """
    Verify a plaintext password against a stored hash.

    Dual-scheme support (pre-run agreement):
      - Hashes starting with 'pbkdf2$' were generated by init_db.py seed
        script using stdlib PBKDF2-HMAC-SHA256.  Verified in-place here.
      - All other hashes are treated as bcrypt digests (production standard).

    This ensures seed accounts (tahir_farmer, sara_buyer) work immediately
    in Run-2 testing without re-seeding the database.
    """
    if stored_hash.startswith(_PBKDF2_PREFIX):
        return _verify_pbkdf2(plaintext, stored_hash)

    # bcrypt path (all new registrations from Run-2 onward)
    try:
        return bcrypt.checkpw(
            plaintext.encode("utf-8"),
            stored_hash.encode("utf-8"),
        )
    except Exception:
        return False


def _verify_pbkdf2(plaintext: str, stored_hash: str) -> bool:
    """
    Internal: verify a pbkdf2$<iterations>$<salt_hex>$<hash_hex> hash.
    Mirrors the format written by init_db.py exactly.
    """
    try:
        _, iterations_str, salt_hex, expected_hex = stored_hash.split("$")
        iterations = int(iterations_str)
        salt = bytes.fromhex(salt_hex)
        dk = hashlib.pbkdf2_hmac(
            hash_name="sha256",
            password=plaintext.encode("utf-8"),
            salt=salt,
            iterations=iterations,
        )
        # Constant-time comparison to prevent timing attacks
        return _hmac.compare_digest(dk.hex(), expected_hex)
    except Exception:
        return False


# ---------------------------------------------------------------------------
# 2. Password Complexity Validation
# ---------------------------------------------------------------------------

def validate_password_complexity(password: str) -> tuple[bool, str]:
    """
    Enforce NFR-SEC-008 / AG-API-INC1-003 §3.1 complexity rules:
      - Minimum 8 characters
      - At least one uppercase letter
      - At least one lowercase letter
      - At least one digit

    Returns: (is_valid: bool, error_message: str)
    """
    if len(password) < 8:
        return False, (
            "Password must be at least 8 characters long and contain "
            "at least one uppercase letter, one lowercase letter, and one number."
        )
    if not re.search(r"[A-Z]", password):
        return False, (
            "Password must be at least 8 characters long and contain "
            "at least one uppercase letter, one lowercase letter, and one number."
        )
    if not re.search(r"[a-z]", password):
        return False, (
            "Password must be at least 8 characters long and contain "
            "at least one uppercase letter, one lowercase letter, and one number."
        )
    if not re.search(r"\d", password):
        return False, (
            "Password must be at least 8 characters long and contain "
            "at least one uppercase letter, one lowercase letter, and one number."
        )
    return True, ""


# ---------------------------------------------------------------------------
# 3. JWT Issuance
# ---------------------------------------------------------------------------

def generate_token(user_id: int, farmer_id: int | None, role: str) -> str:
    """
    Issue a signed HS256 JWT following the exact claims structure
    specified in AG-API-INC1-003 §2:

        {
            "user_id":   <int>,
            "farmer_id": <int | null>,
            "role":      "<role_string>",
            "exp":       <unix_timestamp>
        }

    The secret key is read from Flask app config (JWT_SECRET_KEY).
    Expiry: JWT_EXPIRY_SECONDS (default 30 min, NFR-SEC-003).
    """
    expiry = datetime.now(timezone.utc) + timedelta(seconds=JWT_EXPIRY_SECONDS)
    payload = {
        "user_id":   user_id,
        "farmer_id": farmer_id,
        "role":      role,
        "exp":       expiry,
    }
    secret = current_app.config["JWT_SECRET_KEY"]
    return jwt.encode(payload, secret, algorithm="HS256")


# ---------------------------------------------------------------------------
# 4. JWT Validation Helper
# ---------------------------------------------------------------------------

def _decode_token(token: str) -> tuple[dict | None, str | None]:
    """
    Decode and validate a JWT.
    Returns (payload_dict, None) on success or (None, error_message) on failure.
    """
    secret = current_app.config["JWT_SECRET_KEY"]
    try:
        payload = jwt.decode(token, secret, algorithms=["HS256"])
        return payload, None
    except jwt.ExpiredSignatureError:
        return None, "Session expired. Please log in again."
    except jwt.InvalidTokenError:
        return None, "Invalid session. Please log in again."


# ---------------------------------------------------------------------------
# 5. RBAC Guard Decorators
# ---------------------------------------------------------------------------

def token_required(f):
    """
    Decorator: validates Bearer token on every protected request.

    On success:
      - Injects g.user_id, g.farmer_id, g.role into Flask's request context.
      - Calls the wrapped route handler.

    On failure:
      - Returns HTTP 401 with Standard Error Envelope (AG-API-INC1-003 §5).

    Usage:
        @app.route("/api/crops")
        @token_required
        def get_crops():
            farmer_id = g.farmer_id  # safe, Zero-Trust tenant identity
            ...
    """
    @functools.wraps(f)
    def decorated(*args, **kwargs):
        auth_header = request.headers.get("Authorization", "")

        if not auth_header.startswith("Bearer "):
            return jsonify({
                "success": False,
                "error": "Authentication required. Please log in.",
            }), 401

        token = auth_header[len("Bearer "):]
        payload, err = _decode_token(token)

        if err:
            # Distinguish expired vs malformed (§6.3 SRS RBAC Violation Table)
            if "expired" in err.lower():
                return jsonify({"success": False, "error": err}), 401
            return jsonify({"success": False, "error": err}), 401

        # Inject tenant identity into Flask's g (Zero-Trust: never from body)
        g.user_id   = payload.get("user_id")
        g.farmer_id = payload.get("farmer_id")
        g.role      = payload.get("role")

        return f(*args, **kwargs)

    return decorated


def role_required(*allowed_roles: str):
    """
    Decorator factory: restricts a route to one or more RBAC roles.
    MUST be applied AFTER @token_required so g.role is already populated.

    Returns HTTP 403 with Standard Error Envelope if role not in allowed set.

    Usage:
        @app.route("/api/crops", methods=["POST"])
        @token_required
        @role_required("farmer")
        def create_crop():
            ...
    """
    def decorator(f):
        @functools.wraps(f)
        def decorated(*args, **kwargs):
            if g.get("role") not in allowed_roles:
                return jsonify({
                    "success": False,
                    "error": "Access denied. You do not have permission to access this resource.",
                }), 403
            return f(*args, **kwargs)
        return decorated
    return decorator
